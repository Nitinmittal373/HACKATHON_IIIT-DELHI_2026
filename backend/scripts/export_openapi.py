"""Write the API contract (contracts/openapi.json) from the FastAPI app.

The frontend generates its types from this file, so a backend change reaches the frontend
as a type error instead of a runtime surprise. The same run writes the frontend's fallback
for GET /api/meta from the scoring constants, so even with the API down the app draws the
scale the backend defines. No server and no network are needed.
Run from backend/:  python -m scripts.export_openapi
"""

import json
import os
import tempfile
from pathlib import Path

# app.main builds a module-level app on import, which needs a key; none is ever used here.
os.environ.setdefault("TINYFISH_API_KEY", "contract-export-not-a-key")

from app.config import Settings  # noqa: E402
from app.main import create_app  # noqa: E402
from app.meta import build_meta  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
CONTRACT = ROOT / "contracts" / "openapi.json"
META_FALLBACK = ROOT / "frontend" / "src" / "lib" / "meta.fallback.ts"


def contract_text() -> str:
    """The schema with sorted keys, so the same API always gives byte-identical text."""
    with tempfile.TemporaryDirectory() as folder:
        settings = Settings(
            _env_file=None,  # type: ignore[call-arg]
            tinyfish_api_key="contract-export-not-a-key",  # type: ignore[arg-type]
            database_url=f"sqlite:///{Path(folder, 'contract.db').as_posix()}",
        )
        schema = create_app(settings, cache_dir=None).openapi()
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def meta_fallback_text() -> str:
    meta = json.dumps(build_meta().model_dump(mode="json"), indent=2)
    return (
        "// Generated by backend/scripts/export_openapi.py (make contract). Do not edit.\n"
        "// What GET /api/meta answers, for when the API cannot be reached.\n"
        'import type { Meta } from "@/lib/types";\n\n'
        f"export const META_FALLBACK: Meta = {meta};\n"
    )


def main() -> None:
    CONTRACT.parent.mkdir(parents=True, exist_ok=True)
    CONTRACT.write_text(contract_text(), encoding="utf-8", newline="\n")
    META_FALLBACK.write_text(meta_fallback_text(), encoding="utf-8", newline="\n")
    print(f"wrote {CONTRACT.relative_to(ROOT)} and {META_FALLBACK.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
